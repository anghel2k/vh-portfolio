import { createRequire } from 'node:module';
import { readdir, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
const require = createRequire(import.meta.url);
const sharp = require('sharp');
const root = path.resolve(import.meta.dirname, '..');
const publicRoot = path.join(root, 'public');
const output = path.join(publicRoot, 'optimized');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === 'optimized') continue;
    const target = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(target));
    else if (/\.(png|jpe?g)$/i.test(entry.name) && entry.name !== 'og.png') files.push(target);
  }
  return files;
}
const manifest = {};
for (const source of (await walk(publicRoot)).sort()) {
  const url = '/' + path.relative(publicRoot, source).split(path.sep).join('/');
  const meta = await sharp(source).metadata();
  if (!meta.width || !meta.height) continue;
  const id = crypto.createHash('sha256').update(await readFile(source)).update('webp-84-v1').digest('hex').slice(0, 12);
  const widths = [...new Set([480, 960, 1600].map(w => Math.min(w, meta.width)))];
  const variants = [];
  for (const width of widths) {
    const filename = `${id}-${width}.webp`;
    await sharp(source).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 84, effort: 5 }).toFile(path.join(output, filename));
    variants.push({ src: `/optimized/${filename}`, width });
  }
  manifest[url] = variants;
}
await writeFile(path.join(root, 'app/responsiveImages.ts'), '// Generated by scripts/optimize-images.mjs. Originals remain available for full-resolution media.\nexport const responsiveImages: Record<string, { src: string; width: number }[]> = ' + JSON.stringify(manifest, null, 2) + ';\n');
console.log(`Optimized ${Object.keys(manifest).length} raster assets`);
