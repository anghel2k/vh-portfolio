"""Refresh intrinsic image dimensions used to reserve space before lazy loading."""
from pathlib import Path
from PIL import Image
import json, re, xml.etree.ElementTree as ET
root = Path(__file__).resolve().parents[1]
values = {}
for path in sorted((root / 'public').rglob('*')):
    if path.suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp', '.svg'}:
        continue
    try:
        if path.suffix.lower() == '.svg':
            svg = ET.parse(path).getroot()
            box = re.split(r'[ ,]+', svg.attrib.get('viewBox', '').strip())
            if len(box) == 4:
                width, height = float(box[2]), float(box[3])
            else:
                width, height = float(svg.attrib['width']), float(svg.attrib['height'])
        else:
            with Image.open(path) as image:
                width, height = image.size
        values['/' + path.relative_to(root / 'public').as_posix()] = {'width': round(width), 'height': round(height)}
    except (OSError, ValueError, KeyError, ET.ParseError):
        pass
source = '// Generated by scripts/image-dimensions.py from local assets.\n'
source += 'const dimensions: Record<string, { width: number; height: number }> = ' + json.dumps(values, indent=2) + ';\n\n'
source += 'export function imageDimensions(src: string) {\n  return dimensions[src.split("?")[0]] ?? {};\n}\n'
(root / 'app' / 'imageDimensions.ts').write_text(source)
print(f'Recorded {len(values)} image dimensions')
